import { label, scenarioTime } from "../lib/site.mjs";
import { ProposalDecision } from "./decisions";
import { Chip, reviewTone } from "./site-view/zone-panel";

export const PROPOSAL_STATUS = {
  proposed: { tone: "info", text: "Awaiting decision" },
  approved: { tone: "ok", text: "Approved" },
  rejected: { tone: "unk", text: "Rejected" },
};

function Citation({ citation }) {
  return (
    <li className="small">
      <span className="mono">[{citation.handle}]</span> <span className="mono muted">{citation.ref}</span>{" "}
      {citation.review_status ? <Chip tone={reviewTone(citation.review_status)}>Evidence {citation.review_status}</Chip>
        : <span className="muted">· {citation.ref.startsWith("source:") ? "unconfirmed statement" : "site record"}</span>}
    </li>
  );
}

/** One advisor Proposal with its affected parties, follow-up text, decision record and decision form. */
export function ProposalItem({ flag, proposal, site }) {
  const status = PROPOSAL_STATUS[proposal.status];
  return (
    <li className="ev-item proposal">
      <div className="ev-head"><strong>{proposal.action}</strong><Chip tone={status.tone}>{status.text}</Chip></div>
      <p className="meta" style={{ color: "var(--text-2)" }}>{proposal.rationale}</p>
      <p className="meta">Affected: crews {proposal.affected_crews.join(", ") || "—"} · tasks {proposal.affected_tasks.join(", ") || "—"} · zones {proposal.affected_zones.join(", ") || "—"}</p>
      <details>
        <summary>Follow-up sent to the Crew Leads only after approval</summary>
        <blockquote className="q">{proposal.message}</blockquote>
      </details>
      {proposal.status !== "proposed" && (
        <p className="meta">{status.text} by {proposal.decided_by}{proposal.decided_role && ` (${label(proposal.decided_role)})`} · {scenarioTime(proposal.decided_at, site)} · {proposal.decision_reason}</p>
      )}
      <div style={{ marginTop: 8 }}><ProposalDecision flag={flag} proposal={proposal} /></div>
    </li>
  );
}

/** Advisor explanation and Proposals for a Flag (#13). Advisory only: nothing here changes the Flag by itself. */
export default function Advice({ flag, site }) {
  const { advice } = flag;
  return (
    <section className="panel" aria-labelledby={`advice-h-${flag.id}`}>
      <div className="panel-head">
        <h2 id={`advice-h-${flag.id}`}>Advisor</h2>
        <Chip tone="info">LLM proposal · advisory</Chip>
      </div>
      <div className="pad stack">
        {!advice ? (
          <p className="small muted" style={{ margin: 0 }}>No advisor explanation yet. The worker requests one for each open Flag. Nothing is approved without the Superintendent.</p>
        ) : (
          <>
            <p style={{ margin: 0 }}>{advice.explanation}</p>
            {advice.citations.length > 0 && <ul className="plain">{advice.citations.map((citation) => <Citation key={citation.handle} citation={citation} />)}</ul>}
            <p className="meta">Generated by {advice.backend} · {scenarioTime(advice.created_at, site)}. Cited Evidence shows its current review status.</p>
            {advice.proposals.length === 0 ? <p className="small muted" style={{ margin: 0 }}>No proposals.</p> : (
              <ol className="ev-list">{advice.proposals.map((proposal) => <ProposalItem key={proposal.id} flag={flag} proposal={proposal} site={site} />)}</ol>
            )}
          </>
        )}
      </div>
    </section>
  );
}
